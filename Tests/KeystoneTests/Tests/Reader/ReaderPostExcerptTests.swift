import Testing
import WordPressShared

@testable import WordPress

struct ReaderPostExcerptTests {
    /// Mirrors the shape of a Reader API response from CMM-2748: the excerpt
    /// joins the first two paragraphs with a space, while the content keeps
    /// line breaks between them and uses non-breaking spaces.
    @Test
    func excerptMatchingContentAcrossParagraphsIsAutoGenerated() {
        let excerpt =
            "<p>Monday: The coffee machine broke again this morning. \u{a0}We’re out of filters.</p>\n"
        let content = """
            <div class="is-reader">
            <p class="wp-block-paragraph">Monday:</p>



            <p class="wp-block-paragraph">The coffee machine broke again this morning. \u{a0}We’re out of filters.</p>
            </div>
            """

        #expect(isAutoGenerated(excerpt: excerpt, content: content))
    }

    @Test
    func excerptMatchingContentIsAutoGenerated() {
        #expect(
            isAutoGenerated(
                excerpt: "<p>Hello world, this is the post.</p>",
                content: "<p>Hello world, this is the post. More.</p>"
            )
        )
    }

    @Test(arguments: ["An excerpt that was cut short […]", "An excerpt that was cut short…"])
    func excerptWithTruncationMarkerIsAutoGenerated(excerpt: String) {
        #expect(isAutoGenerated(excerpt: excerpt, content: "<p>Unrelated content.</p>"))
    }

    @Test
    func handWrittenExcerptIsNotAutoGenerated() {
        #expect(
            !isAutoGenerated(
                excerpt: "<p>A short summary written by the author.</p>",
                content: "<p>Monday:</p>\n\n<p>The coffee machine broke again.</p>"
            )
        )
    }

    private func isAutoGenerated(excerpt: String, content: String) -> Bool {
        ReaderPost.isAutoGeneratedExcerpt(excerpt.makePlainText(), plainContent: content.makePlainText())
    }
}
